#!/usr/bin/env node

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const TO = process.env.REPORT_TO || 'malcolmgov24@gmail.com';
const FROM = process.env.RESEND_FROM || 'ZARA <onboarding@resend.dev>';
const API_KEY = process.env.RESEND_API_KEY;
const HTML_PATH = path.join(__dirname, '..', 'fintech_projects_interactive.html');

if (!API_KEY) {
  console.error('Missing RESEND_API_KEY. Run: RESEND_API_KEY=... node scripts/send-latest-report-demo.js');
  process.exit(1);
}

function extractDefaultData(html) {
  const marker = 'const DEFAULT_DATA =';
  const markerIndex = html.indexOf(marker);
  if (markerIndex < 0) throw new Error('Could not find DEFAULT_DATA in fintech_projects_interactive.html');

  const start = html.indexOf('[', markerIndex);
  if (start < 0) throw new Error('Could not find DEFAULT_DATA array start');

  let depth = 0;
  let quote = null;
  let escaped = false;
  for (let i = start; i < html.length; i++) {
    const ch = html[i];

    if (quote) {
      if (escaped) escaped = false;
      else if (ch === '\\') escaped = true;
      else if (ch === quote) quote = null;
      continue;
    }

    if (ch === '\'' || ch === '"' || ch === '`') {
      quote = ch;
      continue;
    }
    if (ch === '[') depth++;
    if (ch === ']') {
      depth--;
      if (depth === 0) return html.slice(start, i + 1);
    }
  }
  throw new Error('Could not find DEFAULT_DATA array end');
}

function moneyLabel(r) {
  if (!r || !r.bv) return 'TBD';
  return r.bv.value || r.bv.annual || 'TBD';
}

function firstRemaining(nextSteps) {
  const txt = String(nextSteps || '').replace(/✅/g, '').replace(/⏳/g, '').trim();
  const remaining = txt.split(/\n+/).map(s => s.replace(/^[-•\s]+/, '').trim()).filter(Boolean);
  return remaining.find(s => /remaining|deploy|wire|set |configure|build|add |initialize|approval|env/i.test(s)) || remaining[0] || 'No outstanding next step recorded.';
}

function generateReport(data) {
  const d = data.slice().sort((a, b) => (a.priority || 99) - (b.priority || 99) || (b.pct || 0) - (a.pct || 0));
  const total = d.length;
  const done = d.filter(r => r.status === 'Done').length;
  const inProgress = d.filter(r => r.status === 'In progress').length;
  const avg = total ? Math.round(d.reduce((s, r) => s + (r.pct || 0), 0) / total) : 0;
  const highValue = d.filter(r => r.bv && r.bv.tier === 'High').length;
  const demos = d.filter(r => r.demoUrl).length;
  const topProgress = d.filter(r => r.status === 'In progress').sort((a, b) => (b.pct || 0) - (a.pct || 0)).slice(0, 8);
  const highImpact = d.filter(r => r.bv && r.bv.tier === 'High').slice(0, 8);
  const blockers = d.filter(r => r.status !== 'Done').sort((a, b) => (b.pct || 0) - (a.pct || 0)).slice(0, 10);
  const today = new Date().toLocaleString('en-ZA', { dateStyle: 'medium', timeStyle: 'short' });

  return [
    'Fintech AI Use Case Tracker - Latest Portfolio Report',
    `Generated by ZARA on ${today}`,
    '',
    'Executive Summary',
    `- ${total} total AI use cases tracked.`,
    `- ${done} complete, ${inProgress} in progress, ${avg}% average completion.`,
    `- ${highValue} high-value use cases identified; ${demos} use cases have demo/prototype links recorded.`,
    '- Primary focus: convert the remaining in-progress items into deployed, wired, evidence-backed production capabilities.',
    '',
    'Portfolio Snapshot',
    ...d.map(r => `- UC${String(r.id).padStart(2, '0')} | ${r.project} | ${r.status} | ${r.pct}% | Owner: ${r.assignedTo || r.owner || 'TBD'} | Value: ${moneyLabel(r)}`),
    '',
    'Top In-Progress Priorities',
    ...(topProgress.length ? topProgress.map(r => `- UC${String(r.id).padStart(2, '0')} ${r.project}: ${r.pct}% complete. Next: ${firstRemaining(r.nextSteps)}`) : ['- No active in-progress use cases.']),
    '',
    'High-Value Use Cases',
    ...(highImpact.length ? highImpact.map(r => `- UC${String(r.id).padStart(2, '0')} ${r.project}: ${moneyLabel(r)} (${r.bv.driver || r.bv.tier})`) : ['- No high-value use cases tagged.']),
    '',
    'Recommended Next Actions',
    ...(blockers.length ? blockers.map((r, i) => `${i + 1}. UC${String(r.id).padStart(2, '0')} ${r.project}: ${firstRemaining(r.nextSteps)}`) : ['1. Maintain completed use cases and prepare stakeholder showcase material.']),
    '',
    'Demo Links',
    ...d.filter(r => r.demoUrl).map(r => `- UC${String(r.id).padStart(2, '0')} ${r.project}: ${r.demoUrl}`),
    '',
    'Regards,',
    'ZARA - AI Executive Analyst'
  ].join('\n');
}

async function main() {
  const html = fs.readFileSync(HTML_PATH, 'utf8');
  const dataSource = extractDefaultData(html);
  const sandbox = {};
  vm.runInNewContext(`result = ${dataSource}`, sandbox, { timeout: 1000 });
  const report = generateReport(sandbox.result || []);
  const subject = 'Latest Fintech AI Use Case Tracker Report';
  const htmlBody = report
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/\n/g, '<br>');

  const response = await fetch('https://api.resend.com/emails', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${API_KEY}`,
      'Content-Type': 'application/json'
    },
    body: JSON.stringify({
      from: FROM,
      to: TO,
      subject,
      text: report,
      html: `<div style="font-family:Inter,Arial,sans-serif;line-height:1.55;color:#0f172a">${htmlBody}</div>`
    })
  });

  const payload = await response.json().catch(() => ({}));
  if (!response.ok) {
    throw new Error(payload.message || payload.error || `Resend failed with ${response.status}`);
  }
  console.log(`Email sent to ${TO}. Resend id: ${payload.id || 'unknown'}`);
}

main().catch(error => {
  console.error(error.message || error);
  process.exit(1);
});
